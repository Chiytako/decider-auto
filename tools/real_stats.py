#!/usr/bin/env python3
"""Summarise data/real/all.jsonl -> data/real/stats.md and data/real/split.json.

Stdlib only. Usage:
  python3 tools/real_stats.py --data data/real/all.jsonl --stats data/real/stats.md \
      --split data/real/split.json [--cutoff 2026-10-15T00:00:00Z]
"""
import argparse
import collections
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from extract_transcripts import redact  # noqa: E402

CLS = ("classifier", "classifier_noreason")
RO_HEADS = {"cd", "grep", "rg", "cat", "head", "tail", "ls", "wc", "echo", "sort", "uniq", "awk", "cut",
            "pwd", "which", "file", "stat", "du", "df", "tr"}


def looks_read_only(cmd):
    """Every pipeline segment starts with a read-only utility (sed only with -n, git only log/show/diff/status)."""
    cmd = re.sub(r"'[^']*'|\"(?:\\.|[^\"\\])*\"", "Q", cmd)  # drop quoted args
    if re.search(r"[^2]>\s*[^&/\s]|>>|\btee\b|<<|\$\(", cmd):
        return False
    for seg in re.split(r"&&|\|\||;|\||\n", cmd):
        w = seg.strip().split()
        if not w:
            continue
        if w[0] in RO_HEADS:
            continue
        if w[0] == "sed" and "-n" in w and "-i" not in w:
            continue
        if w[0] == "git" and len(w) > 1 and (w[1] in ("log", "show", "diff", "status") or
                                            (w[1] == "-C" and len(w) > 3 and w[3] in ("log", "show", "diff", "status"))):
            continue
        if w[0] == "find" and not re.search(r"-delete|-exec", seg):
            continue
        return False
    return True


def md_table(rows, headers):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for r in rows:
        out.append("| " + " | ".join(str(x).replace("|", "\\|").replace("\n", " ") for x in r) + " |")
    return "\n".join(out)


def clip(s, n):
    s = re.sub(r"\s+", " ", s or "").strip()
    return s if len(s) <= n else s[:n] + "..."


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="data/real/all.jsonl")
    ap.add_argument("--stats", default="data/real/stats.md")
    ap.add_argument("--split", default="data/real/split.json")
    ap.add_argument("--cutoff", default="2026-10-15T00:00:00Z",
                    help="sessions whose first auto-mode call is at/after this go to eval")
    args = ap.parse_args()

    E = [json.loads(l) for l in open(args.data, encoding="utf-8")]
    n = len(E)
    elig = [e for e in E if e["train_eligible"]]
    cls_blocks = [e for e in E if e["block_source"] in CLS]
    ts = sorted(e["timestamp"] for e in E if e.get("timestamp"))

    L = []
    L.append("# Real auto-mode transcript examples: statistics\n")
    L.append("Generated by `tools/real_stats.py` from `data/real/all.jsonl` "
             "(produced by `tools/extract_transcripts.py`). All data stays local.\n")
    L.append("- examples (tool calls made in auto mode): **%d**" % n)
    L.append("- time range: %s .. %s" % (ts[0], ts[-1]))
    L.append("- sessions: %d (main transcripts + their subagents grouped under the parent session id)"
             % len({e["session_id"] for e in E}))
    L.append("- subagent examples: %d (%.0f%%)" % (sum(e["is_subagent"] for e in E),
                                                   100.0 * sum(e["is_subagent"] for e in E) / n))
    L.append("- `train_eligible` (gated tool, label known, decided by the classifier or unknown-old-CLI, "
             "no user/hook/safety-check involvement): **%d** (allow %d / block %d)" % (
                 len(elig), sum(e["label"] == "allow" for e in elig), sum(e["label"] == "block" for e in elig)))
    L.append("- classifier blocks: **%d** (with rule %d, no-reason %d); unique by exact (tool, input): %d" % (
        len(cls_blocks), sum(e["block_source"] == "classifier" for e in cls_blocks),
        sum(e["block_source"] == "classifier_noreason" for e in cls_blocks),
        len({e["action_key"] for e in cls_blocks})))
    L.append("- block rate among classifier-checked calls: %.2f%%" % (
        100.0 * len(cls_blocks) / max(1, sum(e["classifier_checked"] is True for e in E))))
    L.append("- secret-like strings redacted in all.jsonl: %d in %d examples\n" % (
        sum(e.get("redactions", 0) for e in E), sum(1 for e in E if e.get("redactions"))))

    L.append("## By label / block_source\n")
    c = collections.Counter((e["label"], e["block_source"], e["result_status"]) for e in E)
    L.append(md_table([(k[0], k[1], k[2], v) for k, v in c.most_common()],
                      ["label", "block_source", "result_status", "count"]))

    L.append("\n## Classifier involvement (how we know)\n")
    L.append("`classifier_checked` comes from `permissionDecision.reasonType` (newest CLI), else presence of "
             "`serverClassifierContext` on the tool_result (>=2.1.280), else a tool-name heuristic "
             "(2.1.278, -> null = unknown).\n")
    c = collections.Counter((e["classifier_checked"], e["checked_evidence"], e["skip_reason"]) for e in E)
    L.append(md_table([(k[0], k[1], k[2], v) for k, v in c.most_common()],
                      ["classifier_checked", "evidence", "skip_reason", "count"]))

    L.append("\n## By rule (classifier blocks)\n")
    c = collections.Counter(e["block_rule"] or "(no explanation)" for e in cls_blocks)
    cu = collections.Counter()
    seen = set()
    for e in cls_blocks:
        if e["action_key"] not in seen:
            seen.add(e["action_key"])
            cu[e["block_rule"] or "(no explanation)"] += 1
    sess = collections.defaultdict(set)
    for e in cls_blocks:
        sess[e["block_rule"] or "(no explanation)"].add(e["session_id"])
    L.append(md_table([(k, v, cu[k], len(sess[k])) for k, v in c.most_common()],
                      ["rule", "blocks", "unique inputs", "sessions"]))

    L.append("\n## By tool\n")
    tools = collections.Counter(e["tool_name"] if not e["tool_name"].startswith("mcp__") else "mcp__*"
                                for e in E)
    rows = []
    for t, v in tools.most_common():
        sub = [e for e in E if (e["tool_name"] if not e["tool_name"].startswith("mcp__") else "mcp__*") == t]
        rows.append((t, v, sum(e["classifier_checked"] is True for e in sub),
                     sum(e["train_eligible"] for e in sub),
                     sum(e["block_source"] in CLS for e in sub),
                     sum(e["block_source"] == "user_reject" for e in sub)))
    L.append(md_table(rows, ["tool", "all", "classifier-checked", "train_eligible", "classifier blocks",
                             "user rejects"]))

    L.append("\n## By project directory\n")
    pc = collections.Counter(e["project"] for e in E)
    L.append(md_table([(k, v, sum(e["block_source"] in CLS for e in E if e["project"] == k))
                       for k, v in pc.most_common()], ["project", "examples", "classifier blocks"]))

    L.append("\n## By CLI version\n")
    vc = collections.Counter(e.get("version") for e in E)
    L.append(md_table([(k, v) for k, v in sorted(vc.items(), key=lambda kv: str(kv[0]))], ["version", "count"]))

    L.append("\n## Duplicates and carry-over\n")
    dup_ids = sum(1 for e in E if e["dup_of"])
    L.append("- Tool-use ids duplicated across files (resumed sessions copy history) were dropped before "
             "writing; exact (tool, input, label, rule) repeats kept but marked `dup_of`: %d examples "
             "(%d among classifier blocks)." % (dup_ids, sum(1 for e in cls_blocks if e["dup_of"])))
    L.append("- No denial is duplicated between a subagent transcript and its parent: subagent tool calls "
             "are only stored in the subagent file.")
    rb = sum(1 for e in cls_blocks if e["recent_blocks"])
    L.append("- %d of %d classifier blocks follow another classifier block within the previous %d actions "
             "(the agent retries a variant and is blocked again, often with the same rule)." % (
                 rb, len(cls_blocks), 20))
    ro = [e for e in cls_blocks if e["tool_name"] == "Bash"
          and looks_read_only(e["tool_input"].get("command", ""))]
    L.append("- %d classifier blocks are on commands that look read-only by themselves (e.g. `grep`, "
             "`sed -n`): the verdict is about the transcript (a preceding risky action, unchecked edit, "
             "or prior block), not the command alone. The model must therefore see prior actions." % len(ro))
    for e in ro:
        L.append("  - [%s] `%s`" % (e["block_rule"], clip(redact(e["tool_input"]["command"])[0], 160)))

    L.append("\n## Non-classifier denials (kept, but not classifier imitation targets)\n")
    for e in E:
        if e["block_source"] in ("user_reject", "safety_check"):
            L.append("- %s %s `%s` %s" % (e["block_source"], e["tool_name"],
                                         clip(redact(json.dumps(e["tool_input"], ensure_ascii=False))[0], 140),
                                         "(subagent)" if e["is_subagent"] else ""))

    # ---------------------------------------------------------------- split
    first = {}
    for e in E:
        s = e["session_id"]
        first[s] = min(first.get(s, e["timestamp"]), e["timestamp"])
    train_s = sorted(s for s, t in first.items() if t < args.cutoff)
    eval_s = sorted(s for s, t in first.items() if t >= args.cutoff)

    def side(ss):
        sub = [e for e in E if e["session_id"] in set(ss)]
        return {"sessions": len(ss), "examples": len(sub),
                "train_eligible": sum(e["train_eligible"] for e in sub),
                "classifier_blocks": sum(e["block_source"] in CLS for e in sub),
                "rules": dict(collections.Counter(e["block_rule"] or "(no explanation)"
                                                  for e in sub if e["block_source"] in CLS))}
    split = {
        "method": "time-based, grouped by parent session (subagents follow their parent); a session goes "
                  "to eval if its first auto-mode tool call is at/after the cutoff",
        "cutoff": args.cutoff,
        "key": "session_id",
        "train": side(train_s), "eval": side(eval_s),
        "train_sessions": train_s, "eval_sessions": eval_s,
        "caveats": [
            "Only ~38 real classifier blocks exist; the eval side's blocks come from few sessions "
            "(one long session contributes most), so report per-session / per-rule results, not just a "
            "pooled F1.",
            "Real data is best used as a realistic-distribution EVAL set and as hard negatives (allows) "
            "for training; positives for training should come mainly from synthetic/external data.",
            "Rules seen in eval but not in train exist; evaluate rule-category accuracy only on rules "
            "present in train or treat it as zero-shot.",
        ],
    }
    with open(args.split, "w", encoding="utf-8") as fo:
        json.dump(split, fo, ensure_ascii=False, indent=1)

    L.append("\n## Proposed split (`split.json`)\n")
    L.append("Time-based by session start, cutoff `%s` (subagents stay with their parent session)." % args.cutoff)
    L.append(md_table([(k, split[k]["sessions"], split[k]["examples"], split[k]["train_eligible"],
                        split[k]["classifier_blocks"], ", ".join("%s:%d" % kv for kv in split[k]["rules"].items()))
                       for k in ("train", "eval")],
                      ["side", "sessions", "examples", "train_eligible", "classifier blocks", "rules"]))
    for cv in split["caveats"]:
        L.append("- " + cv)

    # ---------------------------------------------------------------- examples
    L.append("\n## 10 representative classifier denials (secrets redacted)\n")
    picked, rules = [], set()
    for e in sorted(cls_blocks, key=lambda e: (e["recent_blocks"] != [], e["is_subagent"], e["timestamp"])):
        r = e["block_rule"] or "(no explanation)"
        if r in rules:
            continue
        rules.add(r)
        picked.append(e)
        if len(picked) == 10:
            break
    for i, e in enumerate(picked, 1):
        L.append("### %d. [%s] %s, %s%s" % (i, e["block_rule"] or "no explanation", e["tool_name"],
                                           e["timestamp"][:16], " (subagent)" if e["is_subagent"] else ""))
        inp = e["tool_input"].get("command") if e["tool_name"] == "Bash" else json.dumps(e["tool_input"],
                                                                                           ensure_ascii=False)
        L.append("```\n%s\n```" % redact(clip(inp, 600))[0])
        if e["user_messages"]:
            L.append("- last user message: %s" % redact(clip(e["user_messages"][-1], 260))[0])
        for p in e["prior_actions"][-2:]:
            L.append("- prior: `%s`" % redact(clip(p, 200))[0].replace("`", "'"))
        L.append("")
    with open(args.stats, "w", encoding="utf-8") as fo:
        fo.write("\n".join(L) + "\n")
    print("wrote %s and %s" % (args.stats, args.split), file=sys.stderr)


if __name__ == "__main__":
    main()
